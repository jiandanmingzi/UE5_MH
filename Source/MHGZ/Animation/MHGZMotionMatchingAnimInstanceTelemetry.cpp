void UMHGZMotionMatchingAnimInstance::CaptureParsedInputEvents(const AMHGZCharacter* Character,
	const float WorldTimeSeconds)
{
	const UMHGZWeaponInputRouterComponent* InputRouter = GetInputRouter(Character);
	if (!InputRouter)
	{
		return;
	}

	const TArray<FWeaponInputCaptureEvent>& Events = InputRouter->GetInputCaptureEvents();
	if (Events.IsEmpty())
	{
		return;
	}
	// Router teardown/possession restarts its monotonic serial. Start following
	// the new stream rather than permanently discarding its events.
	if (Events.Last().Serial < RuntimeTelemetryLastObservedInputEventSerial)
	{
		RuntimeTelemetryLastObservedInputEventSerial = 0;
	}
	if (RuntimeTelemetryLastObservedInputEventSerial != 0
		&& Events[0].Serial > RuntimeTelemetryLastObservedInputEventSerial + 1)
	{
		UE_LOG(LogMHGZMM, Warning,
			TEXT("[RuntimeTelemetry] Input event buffer overflowed: missing serials %llu-%llu."),
			static_cast<unsigned long long>(RuntimeTelemetryLastObservedInputEventSerial + 1),
			static_cast<unsigned long long>(Events[0].Serial - 1));
	}

	for (const FWeaponInputCaptureEvent& Event : Events)
	{
		if (Event.Serial <= RuntimeTelemetryLastObservedInputEventSerial)
		{
			continue;
		}
		RuntimeTelemetryLastObservedInputEventSerial = Event.Serial;
		const FWeaponInputSnapshot& Snapshot = Event.Snapshot;
		TArray<FString> Fields;
		Fields.Reserve(16);
		Fields.Add(ToCSVDouble(WorldTimeSeconds));
		Fields.Add(FString::Printf(TEXT("%llu"), static_cast<unsigned long long>(GFrameCounter)));
		Fields.Add(FString::Printf(TEXT("%llu"), static_cast<unsigned long long>(Event.Serial)));
		Fields.Add(ToCSVDouble(Snapshot.Timestamp));
		Fields.Add(ToCSVString(Snapshot.ResolvedInputTag.ToString()));
		Fields.Add(ToCSVString(Snapshot.SourceControlTag.ToString()));
		Fields.Add(ToCSVString(Snapshot.HeldModifierTags.ToStringSimple()));
		Fields.Add(ToCSVString(Snapshot.ContextTags.ToStringSimple()));
		Fields.Add(ToCSVString(ToInputPhaseString(Snapshot.Phase)));
		Fields.Add(FString::FromInt(static_cast<int32>(Snapshot.SequenceID)));
		Fields.Add(ToCSVFloat(Snapshot.RawMoveInput.X));
		Fields.Add(ToCSVFloat(Snapshot.RawMoveInput.Y));
		Fields.Add(ToCSVFloat(Snapshot.WorldDirection.X));
		Fields.Add(ToCSVFloat(Snapshot.WorldDirection.Y));
		Fields.Add(ToCSVFloat(Snapshot.WorldDirection.Z));
		Fields.Add(ToCSVString(ToDirectionString(Snapshot.Direction)));
		RuntimeTelemetryParsedInputPendingRows.Add(FString::Join(Fields, TEXT(",")));
	}
}

