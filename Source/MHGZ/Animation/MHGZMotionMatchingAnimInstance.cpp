void UMHGZMotionMatchingAnimInstance::DrainMMSelectionEvents()
{
	FMotionMatchingSelectionEvent Event;
	while (MMPendingSelectionEvents.Dequeue(Event))
	{
		const int32 NodeIndex = static_cast<int32>(Event.Node);
		if (NodeIndex >= 0 && NodeIndex < UE_ARRAY_COUNT(MMLatestSelection)
			&& (!bHasLatestSelection[NodeIndex] || Event.Frame >= MMLatestSelection[NodeIndex].Frame))
		{
			MMLatestSelection[NodeIndex] = Event;
			bHasLatestSelection[NodeIndex] = true;
		}

		if (!bRuntimeTelemetryActive)
		{
			continue;
		}

		const TCHAR* NodeName = Event.Node == EMHGZMotionMatchingNode::Sheathed
			? TEXT("Sheathed") : TEXT("Unsheathed");
		const FString DatabasePath = Event.Database.IsValid()
			? Event.Database->GetPathName() : TEXT("None");
		const FString AnimationPath = Event.Animation.IsValid()
			? Event.Animation->GetPathName() : TEXT("None");
		// These query values are the values supplied to the Motion Matching node
		// that produced this queued result. Candidate values are sampled directly
		// from the selected asset at SelectedTime. The weighted values are only
		// raw scalar diagnostics; Pose Search's normalized per-channel costs are
		// intentionally not claimed here.
		const float CandidateIntent = EvaluateSelectedCurve(Event, FName(TEXT("MM_Intent")));
		const float CandidateDistance = EvaluateSelectedCurve(Event, FName(TEXT("MM_DistanceToStop")));
		const float CandidateStopGait = EvaluateSelectedCurve(Event, FName(TEXT("MM_StopGait")));
		const float CandidateMoveGait = EvaluateSelectedCurve(Event, FName(TEXT("MM_MoveGait")));
		const float IntentDelta = CandidateIntent - MMIntentQuery;
		const float DistanceDelta = CandidateDistance - MMDistanceToStopQuery;
		const float StopGaitDelta = CandidateStopGait - MMStopGaitQuery;
		const float MoveGaitDelta = CandidateMoveGait - MMMoveGaitQuery;

		TArray<FString> Fields;
		Fields.Reserve(32);
		Fields.Append({ FString::Printf(TEXT("%llu"), static_cast<unsigned long long>(Event.Frame)),
			NodeName, ToCSVString(DatabasePath), ToCSVString(AnimationPath), ToCSVFloat(Event.AnimationTime),
			ToCSVFloat(Event.SearchCost), ToCSVFloat(Event.WantedPlayRate), TEXT("1"),
			Event.bIsContinuing ? TEXT("1") : TEXT("0"), Event.bIsLooping ? TEXT("1") : TEXT("0"),
			Event.bIsMirrored ? TEXT("1") : TEXT("0"), ToCSVFloat(MMIntentQuery),
			ToCSVFloat(MMDistanceToStopQuery), ToCSVFloat(MMStopGaitQuery), ToCSVFloat(MMMoveGaitQuery),
			ToCSVFloat(CandidateIntent), ToCSVFloat(CandidateDistance), ToCSVFloat(CandidateStopGait),
			ToCSVFloat(CandidateMoveGait), ToCSVFloat(IntentDelta), ToCSVFloat(DistanceDelta),
			ToCSVFloat(StopGaitDelta), ToCSVFloat(MoveGaitDelta),
			ToCSVFloat(RuntimeTelemetryIntentWeight * FMath::Square(IntentDelta)),
			ToCSVFloat(RuntimeTelemetryDistanceToStopWeight * FMath::Square(DistanceDelta)),
			ToCSVFloat(RuntimeTelemetryStopGaitWeight * FMath::Square(StopGaitDelta)),
			ToCSVFloat(RuntimeTelemetryMoveGaitWeight * FMath::Square(MoveGaitDelta)),
			ToCSVFloat(Event.LoopPhaseQuery.X), ToCSVFloat(Event.LoopPhaseQuery.Y),
			ToCSVString(Event.LoopQuerySource.ToString()), FString::FromInt(Event.LoopHistoryEntriesRemoved),
			FString::FromInt(Event.PreBlendActivePlayers) });
		RuntimeTelemetryMMSelectionPendingRows.Add(FString::Join(Fields, TEXT(",")));
	}
}

void UMHGZMotionMatchingAnimInstance::DiscardMMSelectionEvents()
{
	FMotionMatchingSelectionEvent DiscardedEvent;
	while (MMPendingSelectionEvents.Dequeue(DiscardedEvent))
	{
	}
}

void UMHGZMotionMatchingAnimInstance::ClearMMRuntimeSelections()
{
	for (bool& bHasSelection : bHasLatestSelection)
	{
		bHasSelection = false;
	}
	for (FMotionMatchingSelectionEvent& Selection : MMLatestSelection)
	{
		Selection = FMotionMatchingSelectionEvent();
	}
}

const UMHGZMotionMatchingAnimInstance::FMotionMatchingSelectionEvent*
UMHGZMotionMatchingAnimInstance::GetLatestSelection(
	const EMHGZMotionMatchingNode MotionMatchingNode) const
{
	const int32 NodeIndex = static_cast<int32>(MotionMatchingNode);
	return NodeIndex >= 0 && NodeIndex < UE_ARRAY_COUNT(MMLatestSelection)
		&& bHasLatestSelection[NodeIndex]
		? &MMLatestSelection[NodeIndex]
		: nullptr;
}

float UMHGZMotionMatchingAnimInstance::GetPredictedForwardDistance(const float TimeInSeconds,
	const FVector& Origin, const FVector& TrajectoryForward) const
{
	for (const FTransformTrajectorySample& Sample : MMPredictedTrajectory.Samples)
	{
		if (FMath::IsNearlyEqual(Sample.TimeInSeconds, TimeInSeconds, KINDA_SMALL_NUMBER))
		{
			return FVector::DotProduct(Sample.Position - Origin, TrajectoryForward);
		}
	}
	return 0.0f;
}

