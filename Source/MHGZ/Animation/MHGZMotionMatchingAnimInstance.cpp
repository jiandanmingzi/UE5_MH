	const FString PoseSearchTracePath = RuntimeTelemetryPoseSearchTraceFilePath;
	const FString PoseSearchDetailDirectory = RuntimeTelemetryPoseSearchDetailDirectory;
	const bool bExportPoseSearchDetail = bRuntimeTelemetryPoseSearchTraceActive;
	const int32 PoseSearchTopN = RuntimeTelemetryPoseSearchTopN;
